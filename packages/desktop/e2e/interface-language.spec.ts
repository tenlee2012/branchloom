import { expect, test } from '@playwright/test'
import { DEMO_PROJECT_PATH, expectNoRuntimeErrors, resetDemo, watchRuntimeErrors } from './helpers/demo'

test.describe('English interface', () => {
  test.use({ locale: 'en-US' })

  test('shows an existing family tree and kinship in English without renaming family records', async ({ page }, testInfo) => {
    const errors = watchRuntimeErrors(page)
    await resetDemo(page, 'en')
    const closeResearch = page.getByRole('button', { name: 'Close relationship research view', exact: true })
    if (await closeResearch.isVisible()) await closeResearch.click()
    await expect(page.getByTestId('family-graph').locator('canvas').first()).toBeVisible()
    await page.getByRole('button', { name: 'Fit to canvas', exact: true }).click()
    await page.screenshot({ path: testInfo.outputPath('english-family-tree.png') })
    await page.goto(`${DEMO_PROJECT_PATH}/kinship?from=person-lin-chen&to=person-lin-hai`)
    await expect(page.locator('[data-kinship-direction="forward"]')).toContainText('father')
    await expect(page.locator('[data-kinship-direction="reverse"]')).toContainText('daughter')
    await expect(page.locator('.kinship-view__path')).toContainText('林晨 → father: 林海')
    await page.getByRole('button', { name: 'Swap people', exact: true }).click()
    await expect(page.locator('[data-kinship-direction="forward"]')).toContainText('daughter')
    await expect(page.locator('[data-kinship-direction="reverse"]')).toContainText('father')
    expectNoRuntimeErrors(errors)
  })

  test('creates records in English, preserves original content and switches language only after confirmation', async ({ page }, testInfo) => {
    const errors = watchRuntimeErrors(page)
    await page.goto('/new')
    await expect(page.locator('html')).toHaveAttribute('lang', 'en')
    await expect(page.getByRole('heading', { name: 'Start with a name' })).toBeVisible()
    await page.getByRole('button', { name: 'Create family tree', exact: true }).click()
    await expect(page.getByText('Enter a project name.', { exact: true })).toBeVisible()
    await page.getByRole('textbox', { name: 'Project name', exact: true }).fill('English interface test')
    await page.getByLabel('Description (optional)').fill('虚构的语言测试资料')
    await page.getByRole('button', { name: 'Create family tree', exact: true }).click()
    await expect(page).toHaveURL(/\/project\/[^/]+\/tree$/)
    await expect(page).toHaveTitle('Family tree · Branchloom')
    await page.getByRole('link', { name: 'People', exact: true }).click()
    await page.getByRole('button', { name: 'New person', exact: true }).click()
    const editor = page.getByRole('region', { name: 'New person', exact: true })
    await editor.getByRole('textbox', { name: 'Primary name', exact: true }).fill('有谱')
    await editor.getByLabel('Birth date', { exact: true }).fill('约 1995 年')
    await editor.getByRole('tab', { name: 'Life story', exact: true }).click()
    await editor.getByLabel('Internal research notes', { exact: true }).fill('人物资料原文保持不变')
    await editor.getByRole('button', { name: 'Save', exact: true }).click()
    await expect(editor).toBeHidden()
    await expect(page).toHaveURL(/\/people\/[^/]+$/)
    await expect(page.getByRole('heading', { name: '有谱', exact: true })).toBeVisible()
    await expect(page.getByText('约 1995 年', { exact: true }).first()).toBeVisible()
    await page.getByRole('tab', { name: 'Life story', exact: true }).click()
    await expect(page.locator('[data-person-notes] > p')).toHaveText('人物资料原文保持不变')
    await page.getByRole('tab', { name: 'Overview', exact: true }).click()
    await page.screenshot({ path: testInfo.outputPath('english-person.png') })

    const language = page.getByRole('combobox', { name: 'Interface language', exact: true })
    await language.selectOption('zh-CN')
    let confirmation = page.getByRole('dialog', { name: 'Change interface language?', exact: true })
    await expect(confirmation).toBeVisible()
    await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(language).toHaveValue('system')
    await expect(page.locator('html')).toHaveAttribute('lang', 'en')

    await language.selectOption('zh-CN')
    confirmation = page.getByRole('dialog', { name: 'Change interface language?', exact: true })
    await confirmation.getByRole('button', { name: 'Save and switch', exact: true }).click()
    await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN')
    await expect(page.getByRole('navigation', { name: '项目导航', exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: '有谱', exact: true })).toBeVisible()
    await expect(page.getByText('约 1995 年', { exact: true }).first()).toBeVisible()
    await page.reload()
    await expect(page.getByRole('combobox', { name: '界面语言', exact: true })).toHaveValue('zh-CN')
    await page.getByRole('combobox', { name: '界面语言', exact: true }).selectOption('system')
    await page.getByRole('dialog', { name: '切换界面语言？', exact: true }).getByRole('button', { name: '保存并切换', exact: true }).click()
    await expect(page.locator('html')).toHaveAttribute('lang', 'en')
    await expect(page.getByRole('heading', { name: '有谱', exact: true })).toBeVisible()
    expectNoRuntimeErrors(errors)
  })

  test('keeps English navigation, language selection and keyboard dialogs accessible on narrow screens', async ({ page }, testInfo) => {
    const errors = watchRuntimeErrors(page)
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/new')
    expect(await page.locator('html').evaluate(element => element.scrollWidth)).toBeLessThanOrEqual(390)
    await page.getByRole('textbox', { name: 'Project name', exact: true }).fill('English mobile test')
    await page.getByRole('button', { name: 'Create family tree', exact: true }).click()
    await expect(page).toHaveURL(/\/project\/[^/]+\/tree$/)
    const projectPath = new URL(page.url()).pathname.replace(/\/tree$/, '')
    const menuButton = page.getByRole('button', { name: 'Open menu', exact: true })
    await menuButton.focus()
    await page.keyboard.press('Enter')
    const menu = page.getByRole('dialog', { name: 'Project menu', exact: true })
    await expect(menu.getByRole('link', { name: 'People', exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(menuButton).toBeFocused()

    for (const suffix of ['people', 'timeline', 'sources', 'kinship', 'manage/overview', 'manage/settings', 'manage/exchange', 'manage/history', 'manage/checks', 'manage/publication', 'collaboration-sync', 'ai-tools']) {
      await page.goto(`${projectPath}/${suffix}`)
      await expect(page.locator('.app-topbar')).toBeVisible()
      await page.getByRole('button', { name: 'Open menu', exact: true }).click()
      await expect(page.getByRole('combobox', { name: 'Interface language', exact: true })).toBeVisible()
      await page.keyboard.press('Escape')
      expect(await page.locator('html').evaluate(element => element.scrollWidth), suffix).toBeLessThanOrEqual(390)
    }
    await page.getByRole('button', { name: 'Open menu', exact: true }).click()
    await page.screenshot({ path: testInfo.outputPath('english-mobile.png') })
    const language = page.getByRole('combobox', { name: 'Interface language', exact: true })
    await language.focus()
    await language.selectOption('zh-CN')
    await expect(page.getByRole('dialog', { name: 'Change interface language?', exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(language).toBeFocused()
    await expect(language).toHaveValue('system')
    await expect(page.getByRole('dialog', { name: 'Project menu', exact: true })).toBeVisible()
    await language.selectOption('zh-CN')
    await page.getByRole('dialog', { name: 'Change interface language?', exact: true }).getByRole('button', { name: 'Save and switch', exact: true }).click()
    await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN')
    await expect(page.getByRole('button', { name: '打开菜单', exact: true })).toBeVisible()
    await page.goBack()
    await expect(page).toHaveURL(`${projectPath}/collaboration-sync`)
    expectNoRuntimeErrors(errors)
  })
})

test.describe('unsupported system language', () => {
  test.use({ locale: 'fr-FR' })
  test('falls back to a complete English first-run screen', async ({ page }) => {
    await page.goto('/new')
    await expect(page.getByRole('heading', { name: 'Start with a name' })).toBeVisible()
    await expect(page.locator('html')).toHaveAttribute('lang', 'en')
    expect(await page.locator('main').innerText()).not.toMatch(/\p{Script=Han}/u)
  })
})

test.describe('Chinese system language', () => {
  test.use({ locale: 'zh-CN' })
  test('keeps Chinese as the default in a Chinese environment', async ({ page }) => {
    await page.goto('/new')
    await expect(page.getByRole('heading', { name: '从一个名字开始' })).toBeVisible()
    await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN')
  })
})
